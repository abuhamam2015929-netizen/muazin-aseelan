    /**
     * إرجاع مواقيت الصلاة الست ليوم معيّن (month: 1-12, day: 1-31)
     * بصيغة نص "HH:mm,HH:mm,HH:mm,HH:mm,HH:mm,HH:mm" -> فجر،شروق،ظهر،عصر،مغرب،عشاء
     */
    fun getRawTimes(month: Int, day: Int): String {
        val monthArr = MONTHS[(month - 1).coerceIn(0, 11)]
        val idx = (day - 1).coerceIn(0, monthArr.size - 1)
        return monthArr[idx]
    }

    fun getPrayerTimes(month: Int, day: Int): PrayerTimes {
        val parts = getRawTimes(month, day).split(",")
        return PrayerTimes(
            fajr = parts[0],
            shuruq = parts[1],
            dhuhr = parts[2],
            asr = parts[3],
            maghrib = parts[4],
            isha = parts[5]
        )
    }

    fun daysInMonth(month: Int): Int = MONTHS[(month - 1).coerceIn(0, 11)].size
